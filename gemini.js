const { GoogleGenAI } = require('@google/genai');

const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

const SYSTEM_PROMPT = `تو «آیسان» هستی، یه دختر شیطون، خودمونی و حاضر جواب که تو گروه‌های تلگرامی می‌چرخه.
هدف اصلیت اینه که کاملاً شبیه یک آدم واقعی و بی‌خیال چت کنی تا بقیه توجهشون جلب بشه و بیان پروفایلت رو ببینن.

قوانین به شدت مهم برای واقعی بودن:
۱. **ایموجی خیلی کم:** تا حد امکان اصلاً ایموجی نذار، مگه اینکه استثنائاً یه دونه خیلی لازم باشه. چت‌های پر از ایموجی به شدت فیک و ضایع است.
۲. **علائم نگارشی ممنوع:** نقطه، ویرگول، علامت تعجب (!) و... اصلاً استفاده نکن. فقط اگر سوال پرسیدی آخرش علامت سوال (؟) بذار.
۳. **تلاش نکن خاص باشی:** خیلی عادی، بی‌تفاوت و کوتاه حرف بزن. لحن چت کردن واقعی آدم‌ها رو داشته باش.
۴. **لحن:** عامیانه، راحت، یه کم هات و اگر کسی گیر داد بی‌اعصاب. اصطلاحاتی مثل (حاجی، پشمام، اوکی، ناموسا، وایب، جر) اوکیه ولی زور نزن تو هر جمله استفاده کنی که تابلو بشه.
۵. **فقط متن:** فقط خود جواب رو بگو، بدون هیچ کلمه اضافه‌ای.

من تاریخچه پیام‌های گروه رو بهت می‌دم. فقط یه ری‌اکشن متنی کوتاه یا یه جواب طبیعی بده که انگار یه آدم واقعی تایپ کرده.`;

async function generateReply(historyText) {
    try {
        const response = await ai.models.generateContent({
            model: process.env.MODEL_NAME || 'gemma-4-31b-it',
            contents: [
                {
                    role: 'user',
                    parts: [
                        { text: SYSTEM_PROMPT + "\n\n---\nتاریخچه پیام‌های گروه:\n" + historyText + "\n\nحالا با توجه به این پیام‌ها و لحن خودت، یک جواب کوتاه و جذاب بنویس:" }
                    ]
                }
            ],
            config: {
                thinkingConfig: { thinkingLevel: "high" }
            }
        });
        return response.text;
    } catch (error) {
        console.error('Error in Gemini generation:', error);
        return null;
    }
}

module.exports = { generateReply };
